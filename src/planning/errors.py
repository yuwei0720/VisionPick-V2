from __future__ import annotations

from enum import Enum


class PlanningStatus(str, Enum):
    VALID = "VALID"
    PLANNER_UNAVAILABLE = "PLANNER_UNAVAILABLE"
    STATE_UNAVAILABLE = "STATE_UNAVAILABLE"
    STATE_STALE = "STATE_STALE"
    STATE_CHANGED_SINCE_VALIDATION = "STATE_CHANGED_SINCE_VALIDATION"
    INVALID_ROBOT_STATE = "INVALID_ROBOT_STATE"
    ROBOT_MODEL_UNVERIFIED = "ROBOT_MODEL_UNVERIFIED"
    ROBOT_MODEL_MISMATCH = "ROBOT_MODEL_MISMATCH"
    SCENE_UNVERIFIED = "SCENE_UNVERIFIED"
    SCENE_VERSION_MISMATCH = "SCENE_VERSION_MISMATCH"
    FRAME_MISMATCH = "FRAME_MISMATCH"
    JOINT_MAPPING_INVALID = "JOINT_MAPPING_INVALID"
    NO_IK = "NO_IK"
    JOINT_LIMIT_VIOLATION = "JOINT_LIMIT_VIOLATION"
    GOAL_SELF_COLLISION = "GOAL_SELF_COLLISION"
    GOAL_ENV_COLLISION = "GOAL_ENV_COLLISION"
    PAYLOAD_GEOMETRY_UNAVAILABLE = "PAYLOAD_GEOMETRY_UNAVAILABLE"
    PAYLOAD_COLLISION = "PAYLOAD_COLLISION"
    ATTACHED_OBJECT_COLLISION = "ATTACHED_OBJECT_COLLISION"
    PAYLOAD_STATE_MISMATCH = "PAYLOAD_STATE_MISMATCH"
    COMMAND_PATH_COLLISION = "COMMAND_PATH_COLLISION"
    COMMAND_PATH_UNVERIFIABLE = "COMMAND_PATH_UNVERIFIABLE"
    VALIDATION_LEVEL_INSUFFICIENT = "VALIDATION_LEVEL_INSUFFICIENT"
    PROTOCOL_ERROR = "PROTOCOL_ERROR"
    INTERNAL_ERROR = "INTERNAL_ERROR"


class PlanningError(RuntimeError):
    def __init__(self, status: PlanningStatus | str, message: str, *, details: dict | None = None):
        self.status = PlanningStatus(status) if not isinstance(status, PlanningStatus) else status
        self.details = dict(details or {})
        super().__init__(message)
